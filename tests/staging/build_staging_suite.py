#!/usr/bin/env python3
"""Builds tests/staging/level4_staging_integration.sql from the local SQL suite.

The generated script runs the SAME seed + functional tests against a real Supabase project
inside ONE implicit transaction and always ends with an exception, so PostgreSQL rolls
everything back: fixture users, films, wallets, schema "t" — nothing is left behind.
The final error message carries the result: "AFN_STAGING_RESULT pass=N fail=0 ...".
Never touches auth.uid() or any Supabase-owned object (no supabase_shim.sql).
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
seed = (root / "tests/sql/seed.sql").read_text(encoding="utf-8")
seed = seed[: seed.index("create schema if not exists t;")]
tests = (root / "tests/sql/level4_tests.sql").read_text(encoding="utf-8")
vars_ = dict(re.findall(r"^\\set (\w+) '''([^']+)'''", tests, re.M))
body = []
for line in tests.splitlines():
    if line.startswith("\\"): continue
    for k, v in vars_.items(): line = re.sub(r":" + k + r"\b", "'" + v + "'", line)
    line = re.sub(r"^begin;\s*", "", line)
    if line.strip() == "commit;":
        line = "reset role; select set_config('request.jwt.claims', '', true);"
    line = line.replace("(public.admin_overview('xuongphim')->>'members')::int = 2,", "(public.admin_overview('xuongphim')->>'members')::int = 2 + (select xp_members from t.base),")
    body.append(line)
head = r"""-- GENERATED by tests/staging/build_staging_suite.py — do not edit by hand.
-- Real-Supabase integration run of the Level 4 functional suite. ALWAYS ROLLS BACK (see last statement).
create schema t;
create table t.results (n serial, msg text);
grant usage on schema t to anon, authenticated;
grant insert, select on t.results to anon, authenticated;
grant usage on sequence t.results_n_seq to anon, authenticated;
create function t.ok(c boolean, msg text) returns void language plpgsql as $$
begin
  if c is not true then raise exception 'AFN_STAGING_FAIL: %', msg; end if;
  insert into t.results(msg) values (msg);
end $$;
create function t.err(q text, pat text, msg text) returns void language plpgsql as $$
begin
  begin
    execute q;
  exception when others then
    if sqlerrm ~* pat then insert into t.results(msg) values (msg); return; end if;
    raise exception 'AFN_STAGING_FAIL: % (got: %)', msg, sqlerrm;
  end;
  raise exception 'AFN_STAGING_FAIL: % (no error raised)', msg;
end $$;
create function t.as_user(u text) returns void language sql as $$
  select set_config('request.jwt.claims', json_build_object('sub', u, 'role', 'authenticated')::text, true);
$$;
grant execute on all functions in schema t to anon, authenticated;
-- Real projects may already hold real members: counts are asserted relative to this baseline.
create table t.base as select (select count(*) from public.site_memberships where site_id = 'xuongphim') as xp_members;
grant select on t.base to anon, authenticated;
"""
tail = r"""
reset role;
do $$ declare n int; begin
  select count(*) into n from t.results;
  raise exception 'AFN_STAGING_RESULT pass=% fail=0 (rolled back, nothing kept)', n;
end $$;
"""
out = head + "\n-- ===== seed (fixture users @example.test) =====\n" + seed + "\n-- ===== tests =====\n" + "\n".join(body) + tail
(root / "tests/staging/level4_staging_integration.sql").write_text(out, encoding="utf-8")
print("written", len(out), "bytes")
